package model.enums.type;

/**
 * ItemType is an enum that represents the different categories of items
 * available in the game. Each item is associated with one of these types, which
 * define its purpose or usage context in gameplay.
 *
 * Enum values:
 * - WEAPON: Represents items that can be used to deal damage to enemies.
 * - POTION: Represents consumable items that restore health points (HP) when used.
 * - ARMOR: Represents items that provide additional defensive capabilities.
 * - TREASURE: Represents valuable items primarily used for trading or scoring purposes.
 */
public enum ItemType {
    WEAPON,
    POTION,
    ARMOR,
    TREASURE
}

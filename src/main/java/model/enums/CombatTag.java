package model.enums;

/**
 * Enum representing various combat-related tags within the game.
 *
 * This enum includes different categories for both player class types
 * and enemy types, allowing their different roles to be easily identified
 * and categorized during gameplay.
 *
 * - Player classes: MAGE, WARRIOR, ROGUE.
 * - Enemy types: SKELETON, TROLL, ELF, DRAGON, DEMON.
 */
public enum CombatTag {
    MAGE,
    WARRIOR,
    ROGUE,

    //Enemy
    SKELETON,
    TROLL,
    ELF,
    DRAGON,
    DEMON
}
